VkResult CreateDebugUtilsMessengerEXT(VkInstance instance, const VkDebugUtilsMessengerCreateInfoEXT* pCreateInfo, const VkAllocationCallbacks* pAllocator, VkDebugUtilsMessengerEXT* pDebugMessenger) {
    auto func = (PFN_vkCreateDebugUtilsMessengerEXT)vkGetInstanceProcAddr(instance, "vkCreateDebugUtilsMessengerEXT");
    if (func != nullptr) {
        return func(instance, pCreateInfo, pAllocator, pDebugMessenger);
    }
    else {
        return VK_ERROR_EXTENSION_NOT_PRESENT;
    }
}

void DestroyDebugUtilsMessengerEXT(VkInstance instance, VkDebugUtilsMessengerEXT debugMessenger, const VkAllocationCallbacks* pAllocator) {
    auto func = (PFN_vkDestroyDebugUtilsMessengerEXT)vkGetInstanceProcAddr(instance, "vkDestroyDebugUtilsMessengerEXT");
    if (func != nullptr) {
        func(instance, debugMessenger, pAllocator);
    }
}

struct QueueFamilyIndices {
    std::optional<uint32_t> graphicsFamily;
    std::optional<uint32_t> presentFamily;

    bool isComplete() {
        return graphicsFamily.has_value() && presentFamily.has_value();
    }
};

struct SwapChainSupportDetails {
    VkSurfaceCapabilitiesKHR capabilities;
    std::vector<VkSurfaceFormatKHR> formats;
    std::vector<VkPresentModeKHR> presentModes;
};

struct Vertex {
    glm::vec3 pos;
    glm::vec2 texCoord;

    static VkVertexInputBindingDescription getBindingDescription() {
        VkVertexInputBindingDescription bindingDescription{};
        bindingDescription.binding = 0;
        bindingDescription.stride = sizeof(Vertex);
        bindingDescription.inputRate = VK_VERTEX_INPUT_RATE_VERTEX;
        return bindingDescription;
    }

    static std::array<VkVertexInputAttributeDescription, 2> getAttributeDescriptions() {
        std::array<VkVertexInputAttributeDescription, 2> attributeDescriptions{};

        // position
        attributeDescriptions[0].binding = 0;
        attributeDescriptions[0].location = 0;
        attributeDescriptions[0].format = VK_FORMAT_R32G32B32_SFLOAT;
        attributeDescriptions[0].offset = offsetof(Vertex, pos);

        // texcoord
        attributeDescriptions[1].binding = 0;
        attributeDescriptions[1].location = 1;
        attributeDescriptions[1].format = VK_FORMAT_R32G32_SFLOAT;
        attributeDescriptions[1].offset = offsetof(Vertex, texCoord);

        return attributeDescriptions;
    }
};

struct UniformBufferObject {
    alignas(16) glm::mat4 model0;
    alignas(16) glm::mat4 model1;
    alignas(16) glm::mat4 view;
    alignas(16) glm::mat4 proj;
};

// Textured cube vertices (pos + uv) using a 3x2 atlas
// Atlas layout (u,v):
//  row 0 (v in [0, 1/2]): [ Left ][ Front ][ Right ]
//  row 1 (v in [1/2, 1]): [ Back ][ Top   ][ Bottom ]
const std::vector<Vertex> vertices = {
    // Front face (tile: column 1, row 0)
    // tile U: [1/3, 2/3], V: [0, 1/2]
    {{-0.5f, -0.5f,  0.5f}, {1.0f / 3.0f, 0.0f}},
    {{ 0.5f, -0.5f,  0.5f}, {2.0f / 3.0f, 0.0f}},
    {{ 0.5f,  0.5f,  0.5f}, {2.0f / 3.0f, 0.5f}},
    {{-0.5f,  0.5f,  0.5f}, {1.0f / 3.0f, 0.5f}},

    // Back face (tile: column 0, row 1)
    // tile U: [0, 1/3], V: [1/2, 1]
    {{-0.5f, -0.5f, -0.5f}, {0.0f,       0.5f}},
    {{ 0.5f, -0.5f, -0.5f}, {1.0f / 3.0f, 0.5f}},
    {{ 0.5f,  0.5f, -0.5f}, {1.0f / 3.0f, 1.0f}},
    {{-0.5f,  0.5f, -0.5f}, {0.0f,       1.0f}}
};

